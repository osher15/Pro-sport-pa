/**
 * Generated-app lookup. Hebrew and English are supplied positionally at the
 * call site; every other language is resolved through GEN using the English
 * string as the key, so an untranslated label ships as English rather than
 * as a blank or a raw identifier.
 */
export const makeQ = (lang) => {
  if (lang === "he") return (he) => he;
  const table = GEN[lang];
  if (!table) return (he, en) => en;
  return (he, en) => {
    if (Array.isArray(en)) return en.map((item) => (item in table ? table[item] : item));
    return en in table ? table[en] : en;
  };
};

/**
 * Same lookup, with `{name}` placeholders filled after translation — word
 * order around an interpolated value differs per language, so the number
 * cannot simply be concatenated onto a translated fragment.
 */
export const makeF = (lang) => {
  const q = makeQ(lang);
  return (he, en, vars) =>
    String(q(he, en)).replace(/\{(\w+)\}/g, (match, name) =>
      vars && name in vars ? String(vars[name]) : match
    );
};
