/**
 * Language registry and translation tables for Madaf.
 *
 * Two surfaces speak here, and they are deliberately kept apart:
 *
 *   UI  — the Madaf shell itself (landing, workspace, toasts). Keyed by the
 *         English source string, so a missing entry falls back to readable
 *         English instead of a bare key like `landing.hero.title`.
 *   GEN — labels that end up *inside a generated app* and inside the source
 *         code Madaf hands back. Hebrew for these already lives at the call
 *         sites as `q("עברית", "English")`, so GEN only carries the other
 *         languages and is likewise keyed by the English string.
 *
 * Adding a language means: one row in LANGUAGES, one block in UI, one in GEN.
 * Nothing else in the app needs to know the list grew.
 */

/**
 * `dir` drives layout; the bidi algorithm does the rest. `font` is a
 * system-only stack — the build inlines everything and loads no webfonts,
 * so a script we cannot render locally would simply fall back to tofu.
 */
const LATIN = "Inter,-apple-system,'Segoe UI',Roboto,Helvetica,Arial,sans-serif";

export const LANGUAGES = [
  { id: "en", label: "English", dir: "ltr", locale: "en_US", font: LATIN },
  { id: "he", label: "עברית", dir: "rtl", locale: "he_IL", font: "'Noto Sans Hebrew','Arial Hebrew',Arial,sans-serif" },
  { id: "ar", label: "العربية", dir: "rtl", locale: "ar_AE", font: "'Noto Sans Arabic','Geeza Pro',Tahoma,Arial,sans-serif" },
  { id: "zh", label: "中文", dir: "ltr", locale: "zh_CN", font: "'PingFang SC','Hiragino Sans GB','Microsoft YaHei','Noto Sans SC',sans-serif" },
  { id: "ru", label: "Русский", dir: "ltr", locale: "ru_RU", font: LATIN },
  { id: "hi", label: "हिन्दी", dir: "ltr", locale: "hi_IN", font: "'Noto Sans Devanagari','Nirmala UI',Mangal,sans-serif" },
  { id: "es", label: "Español", dir: "ltr", locale: "es_ES", font: LATIN },
  { id: "fr", label: "Français", dir: "ltr", locale: "fr_FR", font: LATIN },
];

export const LANG_BY_ID = LANGUAGES.reduce((acc, lang) => {
  acc[lang.id] = lang;
  return acc;
}, {});

export const DEFAULT_LANG = "en";
const langOr = (id) => LANG_BY_ID[id] || LANG_BY_ID[DEFAULT_LANG];

export const dirOf = (id) => langOr(id).dir;
export const isRtlLang = (id) => langOr(id).dir === "rtl";
export const fontOf = (id) => langOr(id).font;
export const localeOf = (id) => langOr(id).locale;
export const labelOf = (id) => langOr(id).label;

/**
 * Latin and Cyrillic are covered by the theme fonts already shipped; Hebrew,
 * Arabic, Chinese and Devanagari are not, and fall back to tofu without a
 * script-specific stack.
 */
const SCRIPT_FONT_NEEDED = new Set(["he", "ar", "zh", "hi"]);
export const needsScriptFont = (id) => SCRIPT_FONT_NEEDED.has(id);

/**
 * Script ranges are decisive: one Hebrew or Devanagari character settles the
 * question. Latin-script languages cannot be told apart this way, so they are
 * resolved by function words instead — and when even that is inconclusive the
 * caller's current language wins, which is what a user who just picked
 * Español from the switcher expects.
 */
const SCRIPT_TESTS = [
  [/[֐-׿]/, "he"],
  [/[؀-ۿݐ-ݿﭐ-﷿]/, "ar"],
  [/[一-鿿㐀-䶿豈-﫿]/, "zh"],
  [/[Ѐ-ӿ]/, "ru"],
  [/[ऀ-ॿ]/, "hi"],
];

/** Short, high-frequency function words — enough to separate es/fr from en. */
const LATIN_HINTS = [
  [/\b(?:una?|el|la|los|las|para|con|que|mi|por|del|calculadora|aplicaci[oó]n|gestor|panel)\b/i, "es"],
  [/\b(?:une?|le|la|les|des|pour|avec|que|mon|du|calculateur|application|gestion|tableau)\b/i, "fr"],
];

export const detectLang = (text, fallback = DEFAULT_LANG) => {
  const value = String(text || "");
  for (const [re, id] of SCRIPT_TESTS) if (re.test(value)) return id;
  for (const [re, id] of LATIN_HINTS) if (re.test(value)) return id;
  // No script and no hint: keep whatever the user is already working in.
  return LANG_BY_ID[fallback] ? fallback : DEFAULT_LANG;
};

/** Best-effort match of the browser's language onto a supported one. */
export const preferredLang = (tags) => {
  for (const tag of tags || []) {
    const base = String(tag).toLowerCase().split("-")[0];
    if (base === "iw") return "he"; // legacy tag still emitted by some browsers
    if (base === "in") return "hi";
    if (LANG_BY_ID[base]) return base;
  }
  return DEFAULT_LANG;
};

