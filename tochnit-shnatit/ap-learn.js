/* ---------- מנוע השאלות ---------- */
function startMC(qid,lvl){
  const t=window.AP_QUIZZES.find(x=>x.id===qid);
  const pool=shuffle(t.qs.filter(q=>q.l<=lvl)).slice(0,10);
  ST={kind:"mc",id:qid,title:t.name,em:t.em,color:t.color,items:pool.map(q=>{
      const opts=q.a.map((txt,i)=>({txt,ok:i===q.c}));
      const sh=shuffle(opts);
      return {q:q.q, opts:sh, c:sh.findIndex(o=>o.ok), why:q.why};
    }), i:0, score:0, log:[]};
  runQ();
}
function startImg(lvl){
  const all=window.AP_BODY.muscles;
  /* ברמה הקלה — רק שרירים מוכרים ובולטים */
  const easy=["pec","quad","abs","bi","calf","glute","delt","tri"];
  const pool=shuffle(lvl===1?all.filter(m=>easy.includes(m.id)):all).slice(0,10);
  ST={kind:"img",id:"img",title:"זהה את השריר",em:"🧍",color:"#38bdf8",items:pool.map(m=>{
      const wrong=shuffle(all.filter(x=>x.id!==m.id)).slice(0,3);
      const sh=shuffle([{txt:m.name,ok:true},...wrong.map(w=>({txt:w.name,ok:false}))]);
      return {q:"איזה שריר מסומן?", side:m.side, hl:m.id, opts:sh,
              c:sh.findIndex(o=>o.ok), why:`${m.name} (${m.lat}) — ${m.does}`};
    }), i:0, score:0, log:[]};
  runQ();
}
function startTF(){
  ST={kind:"tf",id:"tf",title:"נכון או מיתוס",em:"✅",color:"#34d399",
      items:shuffle(window.AP_MYTHS).slice(0,10).map(m=>{
        const sh=[{txt:"נכון",ok:m.t===true},{txt:"מיתוס",ok:m.t===false}];
        return {q:m.s, opts:sh, c:sh.findIndex(o=>o.ok), why:m.why};
      }), i:0, score:0, log:[]};
  runQ();
}

function runQ(){
  const it=ST.items[ST.i];
  if(!it) return finish();
  const pct=Math.round(ST.i/ST.items.length*100);
  $L("#lbody").innerHTML=`
   <div class="quiz" style="--c:${ST.color}">
     <div class="qtop">
       <b>${ST.em} ${E(ST.title)}</b>
       <span>שאלה ${ST.i+1} מתוך ${ST.items.length}</span>
       <span class="sc">${ST.score} נק׳</span>
     </div>
     <div class="qbar"><i style="width:${pct}%"></i></div>
     ${it.hl?`<div class="qfig">${bodySvg({side:it.side,highlight:it.hl})}</div>`:""}
     <div class="qtext">${E(it.q)}</div>
     <div class="qopts">${it.opts.map((o,i)=>`<button class="qopt" data-a="${i}">${E(o.txt)}</button>`).join("")}</div>
     <div id="qfb"></div>
   </div>`;
  document.querySelectorAll("[data-a]").forEach(b=>b.onclick=()=>answer(+b.dataset.a));
}
function answer(i){
  const it=ST.items[ST.i], ok=(i===it.c);
  if(ok) ST.score+=10;
  ST.log.push({q:it.q, ok});
  document.querySelectorAll(".qopt").forEach((b,k)=>{
    b.disabled=true;
    if(k===it.c) b.classList.add("right");
    else if(k===i) b.classList.add("wrong");
  });
  $L("#qfb").innerHTML=`
    <div class="fb ${ok?"ok":"no"}">
      <b>${ok?"✓ נכון":"✕ לא מדויק"}</b>
      <div>${E(it.why)}</div>
      <button class="btn" id="qnext">${ST.i+1<ST.items.length?"לשאלה הבאה ←":"לסיכום ←"}</button>
    </div>`;
  $L("#qnext").onclick=()=>{ST.i++;runQ();};
  $L("#qfb").scrollIntoView({behavior:"smooth",block:"nearest"});
}
function finish(){
  const pct=Math.round(ST.score/(ST.items.length*10)*100);
  const prev=LS.best[ST.id];
  const isBest = prev==null || pct>prev;
  if(isBest){ LS.best[ST.id]=pct; lsave(); }
  const msg = pct>=90?"מצוין — שליטה מלאה בחומר." : pct>=70?"טוב מאוד. שווה לעבור על מה שפספסת."
            : pct>=50?"סביר. כדאי לחזור על הנושא ולנסות שוב." : "כדאי ללמוד את הנושא ולחזור — זה בדיוק מה שהבוחן נועד לו.";
  const miss=ST.log.filter(l=>!l.ok);
  $L("#lbody").innerHTML=`
   <div class="card done" style="--c:${ST.color}">
     <div class="bigpct">${pct}%</div>
     <b>${ST.score} מתוך ${ST.items.length*10} נקודות</b>
     <p>${E(msg)}</p>
     ${isBest?`<div class="newbest">🏆 שיא אישי חדש!</div>`:`<div class="hint">השיא שלך: ${prev}%</div>`}
     ${miss.length?`<div class="review"><b>לחזור על:</b><ul>${miss.map(m=>`<li>${E(m.q)}</li>`).join("")}</ul></div>`:""}
     <div class="links">
       <button class="btn" id="again">🔄 שוב</button>
       <button class="btn ghost" id="back">← לכל הבחנים</button>
     </div>
   </div>`;
  $L("#again").onclick=()=>{
    if(ST.kind==="mc")      startMC(ST.id, 3);
    else if(ST.kind==="img")startImg(3);
    else                    startTF();
  };
  $L("#back").onclick=()=>{TAB="quiz";viewQuizMenu();};
}

/* ---------- ג. משחק התאמה: שריר ↔ תרגיל ---------- */
function startMatch(){
  const pick=shuffle(window.AP_BODY.muscles).slice(0,6);
  ST={kind:"match",id:"match",
      pairs:pick.map(m=>({id:m.id,name:m.name,ex:m.train[0],color:m.color})),
      sel:null, done:[], tries:0};
  ST.left  = shuffle(ST.pairs);
  ST.right = shuffle(ST.pairs);
  drawMatch();
}
function drawMatch(){
  const doneAll = ST.done.length===ST.pairs.length;
  const cell=(p,side)=>{
    const done=ST.done.includes(p.id);
    const sel = ST.sel && ST.sel.id===p.id && ST.sel.side===side;
    return `<button class="mtile${done?" done":""}${sel?" sel":""}"
       data-m="${p.id}" data-side="${side}" style="--c:${p.color}" ${done?"disabled":""}>
       ${E(side==="l"?p.name:p.ex)}</button>`;
  };
  $L("#lbody").innerHTML=`
   <div class="card">
     <h2>🔗 התאמה — שריר לתרגיל</h2>
     <div class="hint">בוחרים שריר בעמודה הימנית, ואז את התרגיל שמאמן אותו בשמאלית. ניסיונות: ${ST.tries}</div>
     <div class="matchwrap">
       <div class="mcol"><h4>שריר</h4>${ST.left.map(p=>cell(p,"l")).join("")}</div>
       <div class="mcol"><h4>תרגיל</h4>${ST.right.map(p=>cell(p,"r")).join("")}</div>
     </div>
     ${doneAll?`<div class="fb ok"><b>✓ כל ההתאמות הושלמו</b>
        <div>סיימת ב-${ST.tries} ניסיונות (${ST.pairs.length} זוגות — המינימום האפשרי).</div>
        <button class="btn" id="again">🔄 סבב חדש</button>
        <button class="btn ghost" id="back">← חזרה</button></div>`:""}
   </div>`;
  document.querySelectorAll("[data-m]").forEach(b=>b.onclick=()=>{
    const id=b.dataset.m, side=b.dataset.side;
    if(!ST.sel){ ST.sel={id,side}; return drawMatch(); }
    if(ST.sel.side===side){ ST.sel={id,side}; return drawMatch(); }
    ST.tries++;
    if(ST.sel.id===id){ ST.done.push(id); ST.sel=null; }
    else { ST.sel=null; }
    drawMatch();
  });
  if(doneAll){ $L("#again").onclick=startMatch; $L("#back").onclick=()=>{TAB="quiz";viewQuizMenu();}; }
}

/* ---------- ד. משחק מיון: הצלחת הבריאה ---------- */
function startSort(){
  ST={kind:"sort",id:"sort",queue:shuffle(window.AP_FOODS.items),i:0,ok:0,wrong:[]};
  drawSort();
}
function drawSort(){
  const F=window.AP_FOODS, it=ST.queue[ST.i];
  if(!it){
    const pct=Math.round(ST.ok/ST.queue.length*100);
    const prev=LS.best.sort;
    if(prev==null||pct>prev){ LS.best.sort=pct; lsave(); }
    return $L("#lbody").innerHTML=`
      <div class="card done" style="--c:#84cc16">
        <div class="bigpct">${pct}%</div>
        <b>${ST.ok} מתוך ${ST.queue.length} מוינו נכון</b>
        ${ST.wrong.length?`<div class="review"><b>אלה מוינו לא נכון:</b><ul>${
          ST.wrong.map(w=>`<li>${w.em} ${E(w.n)} — שייך ל<b>${E(F.groups.find(g=>g.id===w.g).name)}</b></li>`).join("")}</ul></div>`:""}
        <div class="links"><button class="btn" onclick="LEARN.sort()">🔄 שוב</button>
          <button class="btn ghost" onclick="LEARN.menu()">← חזרה</button></div>
      </div>`;
  }
  $L("#lbody").innerHTML=`
   <div class="card">
     <h2>🍽️ הצלחת הבריאה</h2>
     <div class="qbar"><i style="width:${Math.round(ST.i/ST.queue.length*100)}%"></i></div>
     <div class="sortitem"><span class="fem">${it.em}</span><b>${E(it.n)}</b>
       <small>${ST.i+1} מתוך ${ST.queue.length} · נכון: ${ST.ok}</small></div>
     <div class="sgroups">${F.groups.map(g=>`
       <button class="sgrp" data-g="${g.id}" style="--c:${g.color}">
         <span class="em">${g.em}</span><b>${E(g.name)}</b></button>`).join("")}</div>
     <div id="sfb"></div>
   </div>`;
  document.querySelectorAll("[data-g]").forEach(b=>b.onclick=()=>{
    const g=b.dataset.g, correct=(g===it.g), grp=F.groups.find(x=>x.id===it.g);
    if(correct) ST.ok++; else ST.wrong.push(it);
    document.querySelectorAll("[data-g]").forEach(x=>{
      x.disabled=true;
      if(x.dataset.g===it.g) x.classList.add("right");
      else if(x.dataset.g===g) x.classList.add("wrong");
    });
    $L("#sfb").innerHTML=`<div class="fb ${correct?"ok":"no"}">
      <b>${correct?"✓ נכון":"✕ שייך ל"+E(grp.name)}</b>
      <div>${E(grp.why)}</div>
      <button class="btn" id="snext">הבא ←</button></div>`;
    $L("#snext").onclick=()=>{ST.i++;drawSort();};
  });
}

